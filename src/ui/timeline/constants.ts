/* ------------------------------------------------------------------ *
 * 虚拟滚动
 * ------------------------------------------------------------------ */

/** 渲染窗口相对视口向外扩展的比例（左右各一份，= 左右各多渲染一整屏）。 */
export const OVERSCAN_RATIO = 1

/** 视口相对渲染窗口漂移超过该比例时才重算窗口（触发 React 重渲染）。 */
export const REWINDOW_RATIO = 0.5

/** 播放头越过视口该比例时触发自动跟随。 */
export const FOLLOW_TRIGGER_RATIO = 0.8

/** 自动跟随后播放头落在视口该比例处。 */
export const FOLLOW_TARGET_RATIO = 0.2

/** 自动跟随翻页的动画时长（毫秒）：越过触发点后平滑推进，代替瞬间跳。 */
export const FOLLOW_ANIMATION_MS = 160

/* ------------------------------------------------------------------ *
 * 滚轮平移（阻尼插值）
 * ------------------------------------------------------------------ */

/**
 * 滚轮平移的插值系数（每参考帧的收敛比例，0~1）。
 *
 * 视口不是原生 DOM 滚动，没有惯性，所以自研一层 lerp：滚轮只累积"目标位移"，
 * 每帧让当前位置向目标插值 `WHEEL_LERP` 的比例。目标是"网页平滑滚动"那种
 * **极短动画**（非惯性长尾巴）：0.6 收敛约 100ms，停手即停稳。
 * 越小越飘、越大越跟手。
 */
export const WHEEL_LERP = 0.6

/** 滚轮位移倍率：把 `deltaX/Y` 乘上它再累加，用于整体调节滚轮灵敏度。 */
export const WHEEL_MULTIPLIER = 1.0

/** 滚轮收敛阈值（像素）：目标与当前位置换算成像素小于它就对齐并停止循环。 */
export const WHEEL_SETTLE_THRESHOLD_PX = 0.5

/**
 * 参考帧时长（毫秒）：lerp 按它归一化，保证高刷屏（120/144Hz）与 60Hz 手感一致。
 * `alpha = 1 - (1 - WHEEL_LERP)^(dt / WHEEL_REFERENCE_FRAME_MS)`。
 */
export const WHEEL_REFERENCE_FRAME_MS = 1000 / 60

